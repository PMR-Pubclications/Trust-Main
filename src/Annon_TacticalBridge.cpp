#include <Arduino.h>
#include <WiFi.h>
#include <esp_now.h>
#include <esp_wifi.h>

// --- Trust-Main: Annon Tactical Mesh Bridge ---
// Handles encrypted multi-hop packet relaying, priority queuing, 
// and collision-resistant routing for first responder telemetry.

#const uint8_t UNIT_ID = 1;

// Packet Priority Levels
const uint8_t PRIORITY_ROUTINE = 0;   // Breadcrumbs, status heartbeats
const uint8_t PRIORITY_CRITICAL = 1;  // Man-Down / Emergency SOS

// Unified Tactical Mesh Packet Structure
typedef struct __attribute__((packed)) {
    uint8_t sourceID;
    uint8_t relayID;
    uint32_t sequenceNum;
    uint8_t priority;      // 0 = Routine, 1 = Critical
    uint8_t hopCount;      // Max hops to prevent infinite loops (e.g., max 4)
    double latitude;
    double longitude;
    float altitude;
    uint8_t alertType;     // 0 = Normal, 1 = Man-Down
    unsigned long timestamp;
} TacticalPacket;

// Peer broadcast MAC address (or specific peer group addresses)
uint8_t broadcastAddress[] = {0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF};

// Track seen packets to prevent duplicate relay storms
#const int MAX_SEEN_PACKETS = 30;
struct SeenPacket {
    uint8_t sourceID;
    uint32_t sequenceNum;
};
SeenPacket seenPacketLog[MAX_SEEN_PACKETS];
int seenLogIndex = 0;

bool hasSeenPacket(uint8_t srcID, uint32_t seqNum) {
    for (int i = 0; i < MAX_SEEN_PACKETS; i++) {
        if (seenPacketLog[i].sourceID == srcID && seenPacketLog[i].sequenceNum == seqNum) {
            return true;
        }
    }
    return false;
}

void logSeenPacket(uint8_t srcID, uint32_t seqNum) {
    seenPacketLog[seenLogIndex] = {srcID, seqNum};
    seenLogIndex = (seenLogIndex + 1) % MAX_SEEN_PACKETS;
}

// ESP-NOW Receive Callback with Multi-Hop Relay Logic
void onDataReceived(const uint8_t *macAddr, const uint8_t *incomingData, int len) {
    if (len != sizeof(TacticalPacket)) return;

    TacticalPacket pkt;
    memcpy(&pkt, incomingData, sizeof(TacticalPacket));

    // Drop packet if generated by this unit
    if (pkt.sourceID == UNIT_ID) return;

    // Check duplicate log to prevent broadcast storms
    if (hasSeenPacket(pkt.sourceID, pkt.sequenceNum)) return;
    logSeenPacket(pkt.sourceID, pkt.sequenceNum);

    Serial.print("[MESH RX] Packet from Unit #");
    Serial.print(pkt.sourceID);
    Serial.print(" | Priority: ");
    Serial.println(pkt.priority == PRIORITY_CRITICAL ? "CRITICAL" : "ROUTINE");

    // If packet is critical (Man-Down), log immediately
    if (pkt.alertType == 1) {
        Serial.println("[CRITICAL ALERT] Emergency distress received across tactical mesh!");
    }

    // Multi-Hop Relay: If hop count allows, rebroadcast so it clears terrain obstacles
    if (pkt.hopCount < 3) {
        pkt.relayID = UNIT_ID;
        pkt.hopCount++;

        // Add randomized jitter backoff before relaying to prevent airwave collisions
        delay(random(10, 50));
        
        esp_err_t result = esp_now_send(broadcastAddress, (uint8_t *)&pkt, sizeof(TacticalPacket));
        if (result == ESP_OK) {
            Serial.println("[MESH RELAY] Packet successfully rebroadcast across mesh node.");
        }
    }
}

void initTacticalBridge() {
    WiFi.mode(WIFI_STA);
    
    // Set fixed Wi-Fi channel to ensure all mesh nodes sync instantly
    esp_wifi_set_channel(6, WIFI_SECOND_CHAN_NONE);

    if (esp_now_init() != ESP_OK) {
        Serial.println("[MESH ERROR] ESP-NOW initialization failed.");
        return;
    }

    // Register AES Encryption Key (Local Master Key - LMK)
    // Ensures zero-trust sovereign link security across municipal deployment
    esp_now_set_pmk((uint8_t *)"TFML_SovereignKey");

    esp_now_peer_info_t peerInfo = {};
    memcpy(peerInfo.peer_addr, broadcastAddress, 6);
    peerInfo.channel = 6;  
    peerInfo.encrypt = true; // Enable hardware AES encryption
    
    // Set encryption key for broadcast peer
    uint8_t customLMK[16] = {0x01, 0x23, 0x45, 0x67, 0x89, 0xAB, 0xCD, 0xEF, 
                             0x01, 0x23, 0x45, 0x67, 0x89, 0xAB, 0xCD, 0xEF};
    memcpy(peerInfo.lmk, customLMK, 16);

    if (esp_now_add_peer(&peerInfo) != ESP_OK) {
        Serial.println("[MESH ERROR] Failed to add encrypted broadcast peer.");
    }

    esp_now_register_recv_cb(onDataReceived);
    Serial.println("Annon Tactical Mesh Bridge Initialized [Encrypted & Multi-Hop Active].");
}

void setup() {
    Serial.begin(115200);
    initTacticalBridge();
}

void loop() {
    // Background mesh maintenance loop
    delay(1000);
}
